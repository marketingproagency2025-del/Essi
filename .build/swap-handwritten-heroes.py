TREE = {"en": "", "it": "it", "es": "es", "sq": "sq"}

# The og:image dimensions currently on the page, which is the donor's size and not
# necessarily the hero's. Written out rather than read, so that a page already
# swapped fails its count assertion instead of being silently edited twice.
OLD_DIMS = {
    "blog-social-media": (720, 838),
    "article-1": (1200, 720),
    "blog-catalogues": (984, 704),
    "article-2": (1200, 720),
}


def main():
    wanted = sys.argv[1:] or list(JOBS)
    plan, bad = [], []
    for slug in wanted:
        if slug not in JOBS:
            raise SystemExit("unknown slug %r; known: %s" % (slug, ", ".join(JOBS)))
        job = JOBS[slug]
        w, h = Image.open(os.path.join(SITE, "assets", "img", job["new"] + ".jpg")).size
        for lang, tree in TREE.items():
            rel = ("%s/%s.html" % (tree, slug)) if tree else ("%s.html" % slug)
            fp = os.path.join(SITE, tree, slug + ".html") if tree \
                else os.path.join(SITE, slug + ".html")
            s = io.open(fp, encoding="utf-8", newline="").read()
            old_alt, new_alt = job["alt"][lang]

            # Extension attached on every one of these: see the article-1 warning above.
            # 5 jpg: og:image, twitter:image, primaryImageOfPage, BlogPosting.image, <img src>.
            # 2 webp: the preload and the <source srcset>.
            # 3 alt: og:image:alt and twitter:image:alt carry it as content="", the <img> as
            # alt="", so the bare string is matched rather than any one attribute spelling.
            edits = [
                ("%s.jpg" % job["old"], "%s.jpg" % job["new"], 5),
                ("%s.webp" % job["old"], "%s.webp" % job["new"], 2),
                ('<meta property="og:image:width" content="%d" />' % OLD_DIMS[slug][0],
                 '<meta property="og:image:width" content="%d" />' % w, 1),
                ('<meta property="og:image:height" content="%d" />' % OLD_DIMS[slug][1],
                 '<meta property="og:image:height" content="%d" />' % h, 1),
                (old_alt, new_alt, 3),
            ]
            for old, new, want in edits:
                got = s.count(old)
                if got != want:
                    bad.append("%s: expected %d, found %d: %s" % (rel, want, got, old[:55]))
                    continue
                s = s.replace(old, new)
            plan.append((fp, rel, s))

    if bad:
        print("ABORTED, nothing written:")
        for b in bad:
            print("  " + b)
        return 1

    for fp, rel, s in plan:
        io.open(fp, "w", encoding="utf-8", newline="").write(s)
        print("  wrote %s" % rel)
    print("done, %d pages. run fix-img-dims.py next for the <img> width/height." % len(plan))
    return 0


if __name__ == "__main__":
    sys.exit(main())
